-- Display localization only. Stored in the existing Tooltips.lua to allow /reload.
function UnBotLocale.Text(text, depth)
    if UnBotLocale.language ~= "ruRU" or type(text) ~= "string" then return text end
    depth = depth or 0
    if depth > 6 then return text end
    if UnBotLocale.menuRU.ui[text] then return UnBotLocale.menuRU.ui[text] end
    local plain = text:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "")
    local translated = UnBotLocale.menuRU.ui[plain]
    if translated then
        local first, last = text:find(plain, 1, true)
        if first then return text:sub(1, first - 1)..translated..text:sub(last + 1) end
        return translated
    end
    local first, last = text:find(" - ", 1, true)
    if first then
        return UnBotLocale.Text(text:sub(1, first - 1), depth + 1).." - "
            ..UnBotLocale.Text(text:sub(last + 1), depth + 1)
    end
    return text
end

function UnBotLocale.Message(text)
    if DEFAULT_CHAT_FRAME and DEFAULT_CHAT_FRAME.AddMessage then
        DEFAULT_CHAT_FRAME:AddMessage("|cff69ccf0UnBot|r: "..text)
    end
end

function UnBotLocale.Initialize()
    if UnBotLocale.initialized then return end
    -- Called from InitializeUnBotFrame at ADDON_LOADED, after SavedVariables.
    if UnBotSquadConfig == nil then UnBotSquadConfig = {} end
    if type(UnBotSquadConfig) ~= "table" then return end
    UnBotLocale.language = UnBotSquadConfig.uiLanguage == "enUS" and "enUS" or "ruRU"
    if UnBotLocale.language == "ruRU" then
        for id, text in pairs(UnBotLocale.ru.titles) do UnBotTooltipTitle[id] = text end
        for id, text in pairs(UnBotLocale.ru.help) do UnBotTooltipHelp[id] = text end
        BINDING_HEADER_UnBotFrame = "|cff0000ffПанель управления UnBot|r"
        for i = 1, 10 do
            _G["BINDING_NAME_CLICK UnBotCommandButton"..i..":LeftButton"] = "Кнопка команды UnBot "..i
        end
        _G["BINDING_NAME_CLICK UnBotCommandButtonFunc:LeftButton"] = "Закрыть окна UnBot"
    end
    for name, original in pairs(UnBotLocale.staticFrames) do
        local frame = _G[name]
        if frame and frame.SetText then
            -- The legacy equipment label uses blei00d.TTF, absent on this client.
            -- SetText raises "Font not set" unless a usable font is assigned first.
            if frame.SetFont then
                local font = frame.GetFont and frame:GetFont()
                if (frame.GetFont and not font) or name == "EquipInventoryTitleTextLabel" then
                    frame:SetFont("Fonts\\FRIZQT__.TTF", 12)
                end
            end
            frame:SetText(UnBotLocale.Text(original))
        end
    end
    UnBotLocale.initialized = true
end

function UnBotLocale.ApplyStrategies()
    if UnBotLocale.language ~= "ruRU" then return end
    for _, pair in ipairs({{ClassStrategyCO, UnBotLocale.menuRU.combat},
                           {ClassStrategyNC, UnBotLocale.menuRU.noncombat}}) do
        for id, translated in pairs(pair[2]) do
            local original = pair[1] and pair[1][id]
            if original and original[1] == translated[1] then
                original[2], original[3] = translated[2], translated[3]
            end
        end
    end
end

function UnBotLocale.Menu(source, seen, depth)
    if type(source) ~= "table" then return source end
    seen, depth = seen or {}, depth or 0
    if seen[source] then return seen[source] end
    if depth > 12 then return source end
    local result = {}
    seen[source] = result
    for key, entry in pairs(source) do
        if type(entry) == "table" and type(key) == "number" then
            local copy = {}
            for field, val in pairs(entry) do
                if field == "menuList" then copy[field] = UnBotLocale.Menu(val, seen, depth + 1)
                elseif field == "text" or field == "tooltipTitle" or field == "tooltipText" then
                    copy[field] = UnBotLocale.Text(val)
                else copy[field] = val end
            end
            result[key] = copy
        else result[key] = entry end
    end
    return result
end

function UnBotLocale.Select(language)
    if language ~= "enUS" and language ~= "ruRU" then return false end
    if UnBotSquadConfig == nil then UnBotSquadConfig = {} end
    if type(UnBotSquadConfig) ~= "table" then return false end
    UnBotSquadConfig.uiLanguage = language
    local label = language == "ruRU" and "Русский" or "English"
    UnBotLocale.Message("Выбран язык: "..label..". Для применения выполните /reload.")
    return true
end

function UnBotLocale.WhiteMenu(menu, seen)
    if type(menu) ~= "table" then return menu end
    seen = seen or {}
    if seen[menu] then return menu end
    seen[menu] = true
    for _, entry in pairs(menu) do
        if type(entry) == "table" then
            if type(entry.text) == "string" then
                entry.text = "|cffffffff"..entry.text:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "").."|r"
                entry.colorCode = "|cffffffff"
            end
            if entry.preserveMenuColors then
                -- Class summon keeps its original class colors after localization.
            elseif type(entry.menuList) == "table" then
                UnBotLocale.WhiteMenu(entry.menuList, seen)
            elseif type(entry.menuList) == "function" then
                local build = entry.menuList
                entry.menuList = function(...) return UnBotLocale.WhiteMenu(UnBotLocale.Menu(build(...))) end
            end
        end
    end
    return menu
end

function UnBotLocale.ToolsMenu(source)
    local menu = UnBotLocale.Menu(source)
    table.insert(menu, {
        text = "Язык интерфейса / Language", notCheckable = true, hasArrow = true,
        menuList = {
            {text = "Русский", checked = function()
                return not UnBotSquadConfig or UnBotSquadConfig.uiLanguage ~= "enUS"
            end, func = function() UnBotLocale.Select("ruRU") end},
            {text = "English", checked = function()
                return UnBotSquadConfig and UnBotSquadConfig.uiLanguage == "enUS"
            end, func = function() UnBotLocale.Select("enUS") end},
            {text = "Применить / Apply (/reload)", notCheckable = true,
                func = function() ReloadUI() end},
        },
    })
    return UnBotLocale.WhiteMenu(menu)
end

function UnBotLocale.Announce()
    local label = UnBotLocale.language == "ruRU" and "Русский" or "English"
    UnBotLocale.Message("Язык интерфейса: "..label..". /ublang ru или /ublang en, затем /reload.")
end

function UnBotLocale.Slash(message)
    local key = tostring(message or ""):lower():match("^%s*(.-)%s*$")
    if key == "ru" or key == "ruru" then UnBotLocale.Select("ruRU")
    elseif key == "en" or key == "enus" then UnBotLocale.Select("enUS")
    else
        UnBotLocale.Announce()
        if UnBotSquadConfig and UnBotSquadConfig.uiLanguage
            and UnBotSquadConfig.uiLanguage ~= UnBotLocale.language then
            UnBotLocale.Message("Смена языка ожидает /reload.")
        end
    end
end

SLASH_UNBOTLANGUAGE1 = "/ublang"
SLASH_UNBOTLANGUAGE2 = "/unbotlang"
if SlashCmdList then SlashCmdList["UNBOTLANGUAGE"] = UnBotLocale.Slash end
